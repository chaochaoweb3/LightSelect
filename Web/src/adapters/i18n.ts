if (!i18n.isInitialized) {
  void i18n.use(initReactI18next).init({
    fallbackLng: 'en-US',
    initImmediate: false,
    interpolation: { escapeValue: false },
    lng: document.documentElement.lang === 'en-US' ? 'en-US' : 'zh-CN',
    resources
  })
}

export { i18n }
export const useTranslation = useReactTranslation

export const applyInterfaceLanguage = async (language: InterfaceLanguage): Promise<void> => {
  document.documentElement.lang = language
  await i18n.changeLanguage(language)
}

nativeBridge.on('bootstrap', (event) => { void applyInterfaceLanguage(event.preferences.interfaceLanguage) })
nativeBridge.on('preferences.changed', (event) => {
  if (event.key === 'interfaceLanguage') void applyInterfaceLanguage(event.value)
})
